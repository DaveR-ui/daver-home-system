#!/usr/bin/env bash
# Backup the hub's configuration into one tarball.
#
#   deploy/scripts/backup.sh <destination-directory>
#
# What goes in (one archive):
#   - deploy/config/homeassistant/  — the Home Assistant config, INCLUDING
#     .storage/ (the owner account, the access tokens and the LocalTuya local
#     keys: this is the secret part)
#   - deploy/config/mosquitto/       — the broker config
#   - deploy/docker-compose.yml      — the stack definition
#
# What is left out, and why (never silently):
#   - the recorder database (home-assistant_v2.db*) — Home Assistant writes it
#     while it runs, so a copy taken now would be a torn database. It is
#     history, not configuration, and it is the one thing a restore regenerates.
#   - the HA logs (*.log*) — they grow without bound and are not configuration.
#   - the brand-icon cache (.cache/) — regenerated by Home Assistant on boot.
#   - deploy/config/tuya-local-key-data/ — the harvester's session and device
#     cache; both are re-fetchable from the cloud with a fresh QR login.
#
# The archive contains secrets, so it is created 0600, and the destination must
# be outside the repository: the script refuses to write inside the repo or
# over a git-tracked path. Nothing from the archive is ever echoed.
#
# `.storage/` is owned by the container's root, so an unprivileged run cannot
# read it. The script does not need sudo for that: it streams the directory
# out of the running Home Assistant container instead.
#
# Restore (one paragraph, also in docs/protocols/bring-up-the-hub.md):
#   untar into an empty directory, stop the stack, copy deploy/ back over the
#   repository's deploy/ directory, and start the stack again.
set -euo pipefail
umask 077

usage() {
  echo "usage: $0 <destination-directory>" >&2
  exit 2
}

[ $# -eq 1 ] || usage
DEST=$1

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
DEPLOY_DIR=$(cd -- "$SCRIPT_DIR/.." && pwd)
HA_DIR="$DEPLOY_DIR/config/homeassistant"
STORAGE_DIR="$HA_DIR/.storage"

# --- refuse to write inside the repository -----------------------------------
REPO_ROOT=$(git -C "$DEPLOY_DIR" rev-parse --show-toplevel 2>/dev/null || echo "")
mkdir -p "$DEST"
DEST_ABS=$(cd -- "$DEST" && pwd)

if [ -n "$REPO_ROOT" ]; then
  case "$DEST_ABS" in
    "$REPO_ROOT" | "$REPO_ROOT"/*)
      echo "refusing to write the backup inside the repository: $DEST_ABS" >&2
      exit 3
      ;;
  esac
  if git -C "$REPO_ROOT" ls-files --error-unmatch "$DEST" >/dev/null 2>&1; then
    echo "refusing to overwrite a git-tracked path: $DEST" >&2
    exit 3
  fi
fi

STAMP=$(date +%F-%H%M%S)
ARCHIVE="$DEST_ABS/daver-home-system-backup-$STAMP.tar.gz"

WORK=$(mktemp -d)
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT

STAGE="$WORK/stage"
mkdir -p "$STAGE/config/homeassistant"

# --- the readable part --------------------------------------------------------
tar --create \
    --file "$WORK/backup.tar" \
    --exclude='config/homeassistant/.storage' \
    --exclude='config/homeassistant/home-assistant_v2.db' \
    --exclude='config/homeassistant/home-assistant_v2.db-*' \
    --exclude='config/homeassistant/*.log' \
    --exclude='config/homeassistant/*.log.*' \
    --exclude='config/homeassistant/.cache' \
    --directory "$DEPLOY_DIR" \
    config/homeassistant \
    config/mosquitto \
    docker-compose.yml

# --- .storage: read it directly, or stream it out of the container -------------
# It is appended to the SAME archive (a second tar concatenated onto a gzip
# stream would be invisible: tar stops at the first archive's end marker).
if cp -a "$HA_DIR/.storage" "$STAGE/config/homeassistant/.storage" 2>/dev/null; then
  STORAGE_SOURCE="the config directory"
else
  CONTAINER=$(docker compose -f "$DEPLOY_DIR/docker-compose.yml" ps -q homeassistant 2>/dev/null || true)
  if [ -z "$CONTAINER" ]; then
    echo "cannot read $STORAGE_DIR and the homeassistant container is not running." >&2
    echo "start the stack, or re-run with sudo." >&2
    exit 4
  fi
  docker exec "$CONTAINER" tar --create --file - --directory /config .storage \
    | tar --extract --file - --directory "$STAGE/config/homeassistant"
  STORAGE_SOURCE="the running homeassistant container"
fi

tar --append \
    --file "$WORK/backup.tar" \
    --directory "$STAGE" \
    config/homeassistant/.storage

gzip -9 "$WORK/backup.tar"
mv "$WORK/backup.tar.gz" "$ARCHIVE"
chmod 600 "$ARCHIVE"
trap - EXIT

echo "backup written: $ARCHIVE"
echo "  mode: 0600 (it holds the owner account, tokens and local keys)"
echo "  .storage came from: $STORAGE_SOURCE"
echo "  included: the HA config, the broker config, the compose file and the installed custom_components"
echo "  excluded: the recorder database, the HA logs, the brand-icon cache, the tuya-local-key data dir"
